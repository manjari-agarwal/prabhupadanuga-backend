import {Router} from 'express';
import {cmsAuthenticate,cmsLogin,cmsVerifyOtp,cmsMe,cmsLogout} from './auth.js';
import {cmsPermission} from './permissions.js';
import {listUsers,createUser,updateUser,modules} from './users.controller.js';
import {overview,clicksDaily,moderationList,moderate} from './admin.controller.js';
import {listAuditLogs,auditFilters} from './audit.controller.js';
import {getCmsCalendarMonth,putCmsCalendarMonth} from './calendar.controller.js';
import {listCmsKirtans,createCmsKirtan,updateCmsKirtan,featureCmsKirtan,unfeatureCmsKirtan} from './kirtan.controller.js';
import {contacts,contactStatus,volunteers,volunteerStatus,volunteerCategories,saveVolunteerCategory,sadhanaPractices,saveSadhanaPractice} from './operations.controller.js';
import {listQuizzes,getQuiz,saveQuiz,activateQuiz,deactivateQuiz,quizStats,listSankalps,sankalpStatus,quoteList,saveQuote} from './content-batch.controller.js';
const router=Router();
router.post('/auth/login',cmsLogin);
router.post('/auth/verify-otp',cmsVerifyOtp);
router.use(cmsAuthenticate);
router.get('/auth/me',cmsMe);
router.post('/auth/logout',cmsLogout);
router.get('/permissions/modules',cmsPermission('cms_users','view'),modules);
router.get('/users',cmsPermission('cms_users','view'),listUsers);
router.post('/users',cmsPermission('cms_users','create'),createUser);
router.patch('/users/:id',cmsPermission('cms_users','edit'),updateUser);
router.get('/calendar/:year/:month',cmsPermission('calendar','view'),getCmsCalendarMonth);
router.put('/calendar/:year/:month',cmsPermission('calendar','edit'),putCmsCalendarMonth);
router.get('/kirtans',cmsPermission('kirtan','view'),listCmsKirtans);
router.post('/kirtans',cmsPermission('kirtan','create'),createCmsKirtan);
router.patch('/kirtans/:id',cmsPermission('kirtan','edit'),updateCmsKirtan);
router.post('/kirtans/:id/feature',cmsPermission('kirtan','manage'),featureCmsKirtan);
router.post('/kirtans/:id/unfeature',cmsPermission('kirtan','manage'),unfeatureCmsKirtan);
router.get('/contacts',cmsPermission('contact','view'),contacts);
router.patch('/contacts/:id',cmsPermission('contact','edit'),contactStatus);
router.get('/volunteers',cmsPermission('volunteer','view'),volunteers);
router.patch('/volunteers/:id',cmsPermission('volunteer','edit'),volunteerStatus);
router.get('/volunteer/categories',cmsPermission('volunteer','view'),volunteerCategories);
router.put('/volunteer/categories',cmsPermission('volunteer','manage'),saveVolunteerCategory);
router.get('/sadhana/practices',cmsPermission('sadhana','view'),sadhanaPractices);
router.put('/sadhana/practices',cmsPermission('sadhana','manage'),saveSadhanaPractice);
router.get('/quizzes',cmsPermission('quiz','view'),listQuizzes);
router.get('/quizzes/:id',cmsPermission('quiz','view'),getQuiz);
router.post('/quizzes',cmsPermission('quiz','create'),saveQuiz);
router.put('/quizzes/:id',cmsPermission('quiz','edit'),saveQuiz);
router.post('/quizzes/:id/activate',cmsPermission('quiz','manage'),activateQuiz);
router.post('/quizzes/:id/deactivate',cmsPermission('quiz','manage'),deactivateQuiz);
router.get('/quizzes/:id/stats',cmsPermission('quiz','view'),quizStats);
router.get('/sankalps',cmsPermission('sankalpa','view'),listSankalps);
router.patch('/sankalps/:id',cmsPermission('sankalpa','edit'),sankalpStatus);
router.get('/quotes',cmsPermission('quotes','view'),quoteList);
router.put('/quotes',cmsPermission('quotes','edit'),saveQuote);
router.get('/audit',cmsPermission('audit','view'),listAuditLogs);
router.get('/audit/filters',cmsPermission('audit','view'),auditFilters);
router.get('/dashboard/overview',cmsPermission('dashboard','view'),overview);
router.get('/analytics/donation-clicks/daily',cmsPermission('analytics','view'),clicksDaily);
router.get('/moderation/posts',cmsPermission('moderation','view'),moderationList);
router.patch('/moderation/posts/:id',cmsPermission('moderation','approve'),moderate);
export default router;
